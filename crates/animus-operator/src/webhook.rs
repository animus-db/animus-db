//! The `AnimusCluster` validating admission webhook (S-07e, ADR 0070) — a
//! second, opt-in HTTPS listener in the same `animus-operator` binary,
//! entirely separate from the reconcile loop in [`crate::controller`].
//!
//! **Fast and side-effect free, by design.** The handler in this module
//! does exactly one thing: decode the incoming `AdmissionReview`, run
//! [`crate::validate::validate_spec`] (a pure function, no cluster access)
//! against the new spec (and the old one, for an UPDATE), and answer
//! allowed/denied. It never calls the Kubernetes API, never talks to a
//! pod's admin port, and never blocks on anything but decoding the request
//! body — a webhook the API server calls synchronously on every write, with
//! `failurePolicy: Fail` (`deploy/operator/webhook.yaml`), turns any slower
//! or less reliable behavior directly into cluster-wide write unavailability.
//! The live checks this crate also performs (does a referenced `Secret`
//! actually exist — `crate::controller::validate_encryption_key_secret`)
//! stay reconciler-only for exactly this reason; see `crate::validate`'s own
//! module doc.
//!
//! **Why a plain `hyper` server, not `kube`'s own webhook helpers.** `kube`
//! ships the `AdmissionReview`/`AdmissionRequest`/`AdmissionResponse` types
//! (the `admission` Cargo feature, enabled in this crate's `Cargo.toml`) but
//! no server runtime of its own — an admission webhook is an ordinary HTTPS
//! endpoint the API server POSTs to, and this crate already has the
//! `hyper`/`hyper-util`/`tokio-rustls` stack in its dependency graph for the
//! admin-port client (`admin_client.rs`) and the reconciler's own TLS
//! reading. This module is the mirror image of that client: a server-only
//! TLS acceptor (no client certificate — the API server verifies this
//! webhook's cert via `caBundle`/`inject-ca-from`, but this webhook itself
//! never verifies who's calling, matching the admin port's own no-auth
//! posture, ADR 0020) wrapping the identical `hyper::server::conn::http1`
//! plus `hyper_util::rt::TokioIo` shape `crates/animusd/src/admin.rs::serve`
//! uses for its own accept loop, one real Kubernetes API server call away.
//!
//! **Kubernetes requires TLS for a webhook** — there is no plain-HTTP
//! admission webhook shape at all, unlike the admin port's own optional TLS
//! (ADR 0064). `--webhook-cert`/`--webhook-key` (`main.rs`) are therefore
//! not "TLS if you want it," they are simply "the webhook's own cert/key" —
//! see this crate's own `deploy/operator/README.md` section for the two
//! supported ways to obtain them (a cert-manager `Certificate`, generated by
//! `animus-operator webhook-cert` and applied once; or a hand-issued
//! `kubernetes.io/tls` `Secret` mounted the same way).

