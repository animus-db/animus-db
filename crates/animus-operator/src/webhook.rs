/// The one path the `ValidatingWebhookConfiguration` (`deploy/operator/
/// webhook.yaml`) points its `clientConfig.service.path` at.
pub const VALIDATE_PATH: &str = "/validate";

/// The `AnimusCluster` kind name this webhook expects `AdmissionRequest::
/// kind.kind` to carry — a `ValidatingWebhookConfiguration` correctly
/// scoped to `animusdb.io`/`animusclusters` should never send anything
/// else, but [`handle_review`] checks it explicitly anyway (defense in
/// depth against a misconfigured webhook registration) rather than relying
/// solely on a decode failure to catch the mismatch.
const EXPECTED_KIND: &str = "AnimusCluster";

/// Anything that stops the webhook server from starting at all — a bad
/// cert/key pair, or a port already in use. Once started, a per-request
/// failure (a malformed body, a resource-kind mismatch) is answered as a
/// denial, never as a process error — see [`handle_review`].
#[derive(Debug, thiserror::Error)]
pub enum WebhookError {
    #[error("loading TLS material: {0}")]
    Tls(String),
    #[error("binding webhook listener on {addr}: {source}")]
    Bind {
        addr: SocketAddr,
        #[source]
        source: std::io::Error,
    },
}

/// Build a server-only (no client certificate requested) `tokio_rustls::
/// TlsAcceptor` from a PEM cert chain + private key file pair — the
/// server-side mirror of `admin_client.rs::build_tls_connector`. Assumes a
/// process-global rustls `CryptoProvider` is already installed
/// (`main.rs::run` installs `ring` before this is ever called).
pub fn load_tls_acceptor(cert_path: &Path, key_path: &Path) -> Result<TlsAcceptor, WebhookError> {
    // Read the raw bytes ourselves and parse via `*_slice_iter`/
    // `from_pem_slice` (not `rustls_pki_types`'s own `*_file` helpers) —
    // this workspace's dependency graph enables `rustls-pki-types`'
    // `alloc` feature but not `std` (`admin_client.rs::build_tls_connector`
    // makes the identical choice, for the identical reason), and the
    // slice-based methods work either way.
    let cert_bytes = std::fs::read(cert_path)
        .map_err(|e| WebhookError::Tls(format!("reading cert file {cert_path:?}: {e}")))?;
    let key_bytes = std::fs::read(key_path)
        .map_err(|e| WebhookError::Tls(format!("reading key file {key_path:?}: {e}")))?;
    let certs = rustls_pki_types::CertificateDer::pem_slice_iter(&cert_bytes)
        .collect::<Result<Vec<_>, _>>()
        .map_err(|e| WebhookError::Tls(format!("parsing cert file {cert_path:?}: {e}")))?;
    if certs.is_empty() {
        return Err(WebhookError::Tls(format!(
            "no certificates found in {cert_path:?}"
        )));
    }
    let key = rustls_pki_types::PrivateKeyDer::from_pem_slice(&key_bytes)
        .map_err(|e| WebhookError::Tls(format!("parsing key file {key_path:?}: {e}")))?;

    let provider = Arc::new(rustls::crypto::ring::default_provider());
    let config = rustls::ServerConfig::builder_with_provider(provider)
        .with_protocol_versions(rustls::ALL_VERSIONS)
        .map_err(|e| WebhookError::Tls(format!("selecting TLS protocol versions: {e}")))?
        .with_no_client_auth()
        .with_single_cert(certs, key)
        .map_err(|e| WebhookError::Tls(format!("building TLS server config: {e}")))?;
    Ok(TlsAcceptor::from(Arc::new(config)))
}

/// Run the decoded [`AdmissionReview<AnimusCluster>`] through
/// [`validate::validate_spec`] and build the matching response, wrapped
/// back into a generic [`AdmissionReview<DynamicObject>`] — `kube::core::
/// admission::AdmissionResponse::into_review`'s own return type, since a
/// response carries no typed object, only the (possibly denied) verdict.
///
/// Exposed as a standalone function, over the *decoded* request, precisely
/// so the handler tests below need no socket at all — this is the entire
/// interesting logic of the webhook; `handle_request` (below) is just the
/// HTTP/JSON plumbing around it.
#[must_use]
pub fn handle_review(review: AdmissionReview<AnimusCluster>) -> AdmissionReview<DynamicObject> {
    let request: AdmissionRequest<AnimusCluster> = match review.try_into() {
        Ok(req) => req,
        Err(_) => {
            return AdmissionResponse::invalid(
                "AdmissionReview carried no request (a webhook response body \
                 sent as a request?)",
            )
            .into_review();
        }
    };

    if request.kind.kind != EXPECTED_KIND {
        return AdmissionResponse::from(&request)
            .deny(format!(
                "this webhook only validates {EXPECTED_KIND} — received {:?} \
                 (check the ValidatingWebhookConfiguration's own rules)",
                request.kind.kind
            ))
            .into_review();
    }

    // DELETE carries no `object` to validate — nothing for this webhook to
    // say (the `ValidatingWebhookConfiguration` only registers CREATE/
    // UPDATE anyway, so this is unreachable in production, not a case this
    // webhook is actually asked to police).
    let Some(new) = &request.object else {
        return AdmissionResponse::from(&request).into_review();
    };

    let old = request.old_object.as_ref().map(|o| &o.spec);
    match validate::validate_spec(old, &new.spec) {
        Ok(()) => AdmissionResponse::from(&request).into_review(),
        Err(violations) => {
            let message = violations
                .iter()
                .map(ToString::to_string)
                .collect::<Vec<_>>()
                .join("; ");
            AdmissionResponse::from(&request)
                .deny(message)
                .into_review()
        }
    }
}

fn json_response(
    status: StatusCode,
    body: &AdmissionReview<DynamicObject>,
) -> Response<Full<Bytes>> {
    let bytes = serde_json::to_vec(body).unwrap_or_else(|_| b"{}".to_vec());
    Response::builder()
        .status(status)
        .header("content-type", "application/json")
        .body(Full::new(Bytes::from(bytes)))
        .expect("a fixed set of well-formed headers over a JSON body always builds")
}

/// The `hyper` request handler: only `POST /validate` is meaningful — a
/// method/path mismatch is `404`, never reachable in production since the
/// `ValidatingWebhookConfiguration` only ever posts to
/// [`VALIDATE_PATH`] — everything else always answers `200` with a JSON
/// `AdmissionReview` body (Kubernetes' own contract: an admission webhook's
/// verdict rides the response *body*, not the HTTP status; a malformed
/// request body still gets a `200` carrying a denial via
/// `AdmissionResponse::invalid`, matching `kube::core::admission`'s own
/// documented usage).
async fn handle_request(req: Request<Incoming>) -> Result<Response<Full<Bytes>>, Infallible> {
    if req.method() != Method::POST || req.uri().path() != VALIDATE_PATH {
        return Ok(Response::builder()
            .status(StatusCode::NOT_FOUND)
            .body(Full::new(Bytes::new()))
            .expect("a fixed empty 404 body always builds"));
    }

    let body = match req.into_body().collect().await {
        Ok(collected) => collected.to_bytes(),
        Err(e) => {
            return Ok(json_response(
                StatusCode::OK,
                &AdmissionResponse::invalid(format!("reading request body: {e}")).into_review(),
            ));
        }
    };

    let review: AdmissionReview<AnimusCluster> = match serde_json::from_slice(&body) {
        Ok(r) => r,
        Err(e) => {
            return Ok(json_response(
                StatusCode::OK,
                &AdmissionResponse::invalid(format!("malformed AdmissionReview: {e}"))
                    .into_review(),
            ));
        }
    };

    Ok(json_response(StatusCode::OK, &handle_review(review)))
}

/// Serve the webhook forever on `addr`, TLS-terminated by `acceptor`. Never
/// returns on success (mirrors `crates/animusd/src/admin.rs::serve`'s own
/// accept-loop contract); returns [`WebhookError::Bind`] only if the
/// listener itself can't bind.
///
/// One task per connection, matching `admin.rs::serve`'s own shape — a
/// failed TLS handshake or a connection-serving error is logged and the
/// loop keeps accepting every other connection; nothing here can bring the
/// whole webhook down over one bad peer.
pub async fn run(addr: SocketAddr, acceptor: TlsAcceptor) -> Result<(), WebhookError> {
    let listener = TcpListener::bind(addr)
        .await
        .map_err(|source| WebhookError::Bind { addr, source })?;
    tracing::info!(%addr, "admission webhook listening");
    loop {
        let (stream, peer) = match listener.accept().await {
            Ok(pair) => pair,
            Err(e) => {
                tracing::warn!(error = %e, "webhook accept failed");
                continue;
            }
        };
        let acceptor = acceptor.clone();
        // ADR 0003 / ADR 0061 Decision 4 (rung B5): this crate has no `Env`
        // seam (`crates/animus-operator/CLAUDE.md`'s own note) — a real
        // Kubernetes API server dialing a real socket is outside ADR 0003's
        // determinism scope, the identical allowance every other real-socket
        // accept loop in this crate (`admin_client.rs`'s own request
        // timeout) already carries.
        #[allow(
            clippy::disallowed_methods,
            reason = "animus-operator has no Env seam (see its own CLAUDE.md); the webhook's accept loop is a real Kubernetes API server dialing a real socket, outside ADR 0003's scope"
        )]
        tokio::spawn(async move {
            let tls_stream = match acceptor.accept(stream).await {
                Ok(s) => s,
                Err(e) => {
                    tracing::warn!(error = %e, %peer, "webhook TLS handshake failed");
                    return;
                }
            };
            let io = TokioIo::new(tls_stream);
            if let Err(e) = hyper::server::conn::http1::Builder::new()
                .serve_connection(io, service_fn(handle_request))
                .await
            {
                tracing::debug!(error = %e, %peer, "webhook connection closed");
            }
        });
    }
}

